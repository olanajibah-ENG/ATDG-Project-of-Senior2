"""Gives a checked test its path and its final text.

Nothing is written to disk in this slice: the path and the text are stored on the record, and the
sandbox slice writes them into the workspace it builds.
"""
from core_ai.services.test_generation.context import test_name_stem
from core_ai.services.test_generation.languages.python_adapter import module_name, split_unit_id


def test_path(unit_id, level="unit"):
    """`pkg/game.py::Student.enroll` → `tests/generated/test_pkg_game_Student_enroll__unit.py`"""
    path, _, _ = split_unit_id(unit_id)
    file_stem = module_name(path).replace(".", "_")
    return f"tests/generated/test_{file_stem}_{test_name_stem(unit_id)}__{level}.py"


test_path.__test__ = False      # a helper, not a pytest test


def assemble(code, *, unit_id, body_hash, job_id, level="unit"):
    header = "\n".join([
        "# Generated by AutoTest & DocGen Manager — Feature 1 (Generate Trusted Tests)",
        f"# unit:      {unit_id}",
        f"# level:     {level}",
        f"# body hash: {body_hash}",
        f"# job:       {job_id}",
        "# status:    generated and checked for form only — NOT RUN YET",
        "",
        "",
    ])
    return header + code.strip("\n") + "\n"
