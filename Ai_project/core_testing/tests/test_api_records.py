# ── list ─────────────────────────────────────────────────────────────────────

def test_list_shape_and_total(job):
    response = _get(views.JobRecordsView, job)
    assert response.status_code == 200
    assert response.data["total"] == len(response.data["items"]) == (14 + 6) * 3
    for item in response.data["items"]:
        assert set(item) == {"id", "file", "unit_id", "level", "status", "reason_code", "test_path"}
    assert "test_code" not in json.dumps(response.data)


def test_list_filters(job):
    assert _get(views.JobRecordsView, job, query="?level=unit").data["total"] == 20
    assert _get(views.JobRecordsView, job, query="?level=edge").data["total"] == 20
    assert _get(views.JobRecordsView, job, query="?path=shop/models.py").data["total"] == 18
    assert _get(views.JobRecordsView, job, query="?status=generated").data["total"] == 19
    failed = _get(views.JobRecordsView, job, query="?status=generation_failed").data
    assert [(i["unit_id"], i["reason_code"], i["test_path"]) for i in failed["items"]] == [
        ("game.py::Course.add_student", "no_code", None)]
    both = _get(views.JobRecordsView, job, query="?level=unit&path=shop/models.py&status=generated").data
    assert both["total"] == 6 and {i["file"] for i in both["items"]} == {"shop/models.py"}
    assert _get(views.JobRecordsView, job, query="?status=ready").data == {"items": [], "total": 0}


