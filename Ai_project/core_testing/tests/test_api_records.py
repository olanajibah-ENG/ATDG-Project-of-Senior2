factory = APIRequestFactory()
NOW = datetime(2026, 11, 13, 12, 0, 0)


@pytest.fixture(autouse=True)
def _no_celery(monkeypatch):
    monkeypatch.setattr(views, "_enqueue", lambda job_id: None)


def _headers(user_id=7, auth=True):
    return {"HTTP_AUTHORIZATION": f"Bearer {make_token(user_id=user_id)}"} if auth else {}


def _start(body=None, user_id=7):
    request = factory.post("/x", data=json.dumps(body or {"project_id": PROJECT_ID}),
                           content_type="application/json", **_headers(user_id))
    response = views.JobListView.as_view()(request)
    response.render()
    return response.data["job_id"]


def _get(view, job_id, record_id=None, query="", user_id=7, auth=True):
    request = factory.get("/x" + query, **_headers(user_id, auth))
    kwargs = {"job_id": job_id}
    if record_id is not None:
        kwargs["record_id"] = record_id
    response = view.as_view()(request, **kwargs)
    response.render()
    return response


def _generate(job_id, repo, reader, records, attempts, model=None, max_requests=20):
    run_pass(job_id, repo, reader, lambda f: None, NOW, then_generate=True, record_repo=records)
    facade = LLMFacade(model or FakeModel(), attempts)
    for _ in range(100):
        if repo.get(job_id)["status"] != "running":
            break
        run_generation_pass(job_id, repo, records, attempts, reader, facade, NOW, max_requests=max_requests)


