def test_generated_record_shows_its_code_and_says_it_was_not_run(job):
    item = _get(views.JobRecordsView, job, query="?status=generated&path=game.py").data["items"][0]
    response = _get(views.JobRecordDetailView, job, item["id"])
    assert response.status_code == 200
    data = response.data
    assert data["id"] == item["id"] and data["status"] == "generated"
    assert data["test_code"].startswith("# Generated by") and "def test_" in data["test_code"]
    assert data["executed"] is False and "has not been run" in data["notice"]
    assert (data["model"], data["prompt_version"]) == ("fake/model", "unit-v1")
    assert data["test_path"] == item["test_path"]


def test_failed_and_pending_records_have_no_code(job):
    failed = _get(views.JobRecordsView, job, query="?status=generation_failed").data["items"][0]
    data = _get(views.JobRecordDetailView, job, failed["id"]).data
    assert data["test_code"] is None and data["reason_code"] == "no_code" and data["reason_detail"]
    pending = _get(views.JobRecordsView, job, query="?level=edge").data["items"][0]
    assert _get(views.JobRecordDetailView, job, pending["id"]).data["test_code"] is None


def test_unknown_record_or_record_of_another_job_is_404(job, repo, reader, records, attempts):
    assert _get(views.JobRecordDetailView, job, "t_0000000000").status_code == 404
    other = _start()
    _generate(other, repo, reader, records, attempts)
    foreign = _get(views.JobRecordsView, other).data["items"][0]["id"]
    response = _get(views.JobRecordDetailView, job, foreign)
    assert response.status_code == 404 and response.data["error"]["code"] == "not_found"


# ── access ───────────────────────────────────────────────────────────────────

def test_record_routes_need_a_token_and_the_owner(job):
    some_id = _get(views.JobRecordsView, job).data["items"][0]["id"]
    for view, record_id in ((views.JobRecordsView, None), (views.JobRecordDetailView, some_id)):
        assert _get(view, job, record_id, auth=False).status_code == 401
        stranger = _get(view, job, record_id, user_id=8)
        assert stranger.status_code == 403 and stranger.data["error"]["code"] == "forbidden"
        assert _get(view, job, record_id, user_id=7).status_code == 200
    assert _get(views.JobRecordsView, "job_000000000000").status_code == 404


# ── the job route after generation ───────────────────────────────────────────

def test_job_status_after_generation(job):
    data = _get(views.JobDetailView, job).data
    assert (data["status"], data["stage"], data["error"]) == ("completed_with_issues", "generated", None)
    assert data["progress"]["total"] == 60 and data["progress"]["done"] == 20
    by_status = data["progress"]["by_status"]
    assert (by_status["generated"], by_status["generation_failed"], by_status["pending"], by_status["ready"]) == (19, 1, 40, 0)
    files = {f["path"]: f for f in data["files"]}
    assert files["shop/models.py"]["status"] == "generated"
    assert files["shop/models.py"]["levels"] == {"unit": "generated", "edge": "pending", "integration": "pending"}
    assert files["game.py"]["status"] == "partial" and files["game.py"]["levels"]["unit"] == "partial"


def test_job_status_when_generation_stopped_early(repo, reader, records, attempts, make_project):
    make_project({"game.py": "game.py"})
    job_id = _start({"project_id": PROJECT_ID, "levels": ["unit"]})
    _generate(job_id, repo, reader, records, attempts, FakeModel(fail_from=3))
    data = _get(views.JobDetailView, job_id).data
    assert data["status"] == "completed_with_issues" and data["error"]["code"] == "model_unavailable"
    assert data["progress"]["by_status"]["generated"] == 2 and data["progress"]["by_status"]["pending"] == 12
    assert data["files"][0]["status"] == "partial"


